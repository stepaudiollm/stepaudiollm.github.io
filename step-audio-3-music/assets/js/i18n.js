const LS_KEY = 'sa3m.lang';
let lang = DEFAULT_LANG;
const listeners = new Set();

try {
  const saved = localStorage.getItem(LS_KEY);
  if (saved === 'zh' || saved === 'en') lang = saved;
} catch { /* 隐私模式下 localStorage 会抛错，忽略 */ }

export const getLang = () => lang;

export function setLang(next) {
  if (next !== 'zh' && next !== 'en') return;
  if (next === lang) return;
  lang = next;
  try { localStorage.setItem(LS_KEY, lang); } catch {}
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  listeners.forEach(fn => fn(lang));
}

export const onLangChange = fn => { listeners.add(fn); return () => listeners.delete(fn); };

export function t(key, vars) {
  let s = DICT[lang][key] ?? DICT[DEFAULT_LANG][key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, vars[k]);
  return s;
}

/** 取曲目的本地化字段：title/title_en、tags/tags_en、caption/caption_en */
export function locField(obj, base) {
  if (!obj) return '';
  return (lang === 'en' ? (obj[base + '_en'] ?? obj[base]) : obj[base]) ?? '';
}
